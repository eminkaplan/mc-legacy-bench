#!/usr/bin/env python3
"""Build RESULTS.md: one comparison table per Minecraft version across every submission in results/*/.

usage: aggregate.py            (writes RESULTS.md at the repo root)
Only standard-protocol rows count: view=normal from each submission's summary.csv (not extra/).
Repeats of the same version / GPU / Java are combined by their median.
"""
import csv
import glob
import os
import re
import statistics as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def vkey(v):
    return tuple(int(x) for x in re.findall(r"\d+", v))


def short_gpu(renderer):
    return renderer.split(" (")[0].strip() or "?"


def system_field(md, name):
    m = re.search(r"^\| " + re.escape(name) + r" \| (.*) \|$", md, re.M)
    return m.group(1) if m else "?"


def med(rows, col):
    vals = [float(r[col]) for r in rows if r.get(col) not in (None, "")]
    return st.median(vals) if vals else None


def fmt(x, nd=0):
    return "–" if x is None else f"{x:.{nd}f}"


def main():
    table = {}  # version -> list of rows
    for summary in sorted(glob.glob(os.path.join(ROOT, "results", "*", "summary.csv"))):
        sub = os.path.basename(os.path.dirname(summary))
        md = open(os.path.join(os.path.dirname(summary), "system.md")).read() if os.path.exists(
            os.path.join(os.path.dirname(summary), "system.md")) else ""
        cpu = system_field(md, "CPU").split(",")[0].replace("(R)", "").replace("(TM)", "").replace(" CPU", "")
        rows = [r for r in csv.DictReader(open(summary)) if r.get("view") == "normal"]
        groups = {}
        for r in rows:
            groups.setdefault((r["version"], r["gpu_prime"], short_gpu(r["gpu_renderer"])), []).append(r)
        for (ver, _, gpu), rs in groups.items():
            j8 = [r for r in rs if r["java"] == "8"]
            j21 = [r for r in rs if r["java"] == "21"]
            table.setdefault(ver, []).append(dict(
                sub=sub, cpu=cpu, gpu=gpu, fps8=med(j8, "fps_last30"), fps21=med(j21, "fps_last30"),
                create=med(j8, "create_world_s"), cores8=med(j8, "cpu_cores"), cores21=med(j21, "cpu_cores"),
                runs=len(rs)))

    out = ["# Results", "",
           "Generated by `tools/aggregate.py` from `results/*/summary.csv`; do not edit by hand.",
           "Standard protocol (`suite.sh`): Normal view distance, 854×480, unlimited FPS, 90 s per run.",
           "FPS = in-game F3 counter, mean of the last 30 s; repeats combined by median.",
           "See each submission's `system.md` for the full test system and notes on background load.", ""]
    for ver in sorted(table, key=vkey):
        out += [f"## Minecraft {ver}", "",
                "| Submission | CPU | GPU | FPS Java 8 | FPS Java 21 | World creation, Java 8 (s) | CPU cores Java 8 → 21 | Runs |",
                "| --- | --- | --- | ---: | ---: | ---: | --- | ---: |"]
        for r in sorted(table[ver], key=lambda r: -(r["fps8"] or r["fps21"] or 0)):
            out.append(f"| [{r['sub']}](results/{r['sub']}/system.md) | {r['cpu']} | {r['gpu']} | {fmt(r['fps8'])} | "
                       f"{fmt(r['fps21'])} | {fmt(r['create'], 1)} | {fmt(r['cores8'], 1)} → {fmt(r['cores21'], 1)} | {r['runs']} |")
        out.append("")
    with open(os.path.join(ROOT, "RESULTS.md"), "w") as f:
        f.write("\n".join(out))
    print(f"RESULTS.md: {sum(len(v) for v in table.values())} rows across {len(table)} versions")


if __name__ == "__main__":
    main()
